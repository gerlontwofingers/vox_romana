"""Podcast data models — event aliases and output structures.

Follows the same pattern as debates and audiobooks:
    PodcastEvent = AudioEvent (alias)
    PodcastSegment — groups events for one segment
    MergedPodcast — final serializable output for TTS rendering

The TTS renderer consumes MergedPodcast.to_dict() identically to how it
consumes MergedDebate or MergedAudiobook — it only cares about the events
list, voice_casting, voice_hints, and tts_styles.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from ...core.models import AudioEvent

# ── Event alias ──────────────────────────────────────────────────────────
# Same underlying AudioEvent used by all show types. The alias exists so
# podcast code reads naturally: "list[PodcastEvent]" instead of "list[AudioEvent]".
PodcastEvent = AudioEvent


# ── Segment grouping ────────────────────────────────────────────────────

@dataclass(slots=True, frozen=True)
class PodcastSegment:
    """A segment's worth of conversation events.

    Each segment is generated by a single LLM call and contains multiple
    speakers' turns. This is the defining structural difference from
    debates (one turn per LLM call).

    Attributes:
        segment_id:     Unique ID for this segment (e.g., "seg_001").
        segment_order:  Position in the episode (1-based).
        segment_type:   The kind of segment: "intro", "banter",
                        "deep_dive", "drama", "outro".
        topic:          What this segment is about.
        events:         The conversation events within this segment.
    """

    segment_id: str
    segment_order: int
    segment_type: str
    topic: str = ""
    events: tuple[PodcastEvent, ...] = ()

    def to_dict(self) -> dict[str, Any]:
        return {
            "segment_id": self.segment_id,
            "segment_order": self.segment_order,
            "segment_type": self.segment_type,
            "topic": self.topic,
            "events": [e.to_dict() for e in self.events],
        }


# ── Final output ────────────────────────────────────────────────────────

@dataclass(slots=True, frozen=True)
class MergedPodcast:
    """The complete podcast episode, ready for serialization and TTS rendering.

    This is the podcast equivalent of MergedDebate / MergedAudiobook.
    The TTS renderer doesn't care which show type produced it — it reads
    the events, voice_casting, voice_hints, and tts_styles generically.

    Attributes:
        podcast_id:     Unique ID for this podcast episode.
        title:          Episode title.
        show_name:      The podcast show name (e.g., "Trash Pandas").
        topic:          Main topic of the episode.
        tone:           Overall tone.
        hosts:          Tuple of host names (for metadata).
        segments:       Ordered segments with their events.
        events:         Flat list of ALL events across all segments.
        voice_casting:  Maps speaker name → voice gender ("male"/"female").
        voice_hints:    Maps speaker name → TTS casting note.
        tts_styles:     Maps speaker name → persistent TTS style instruction.
    """

    podcast_id: str
    title: str
    show_name: str | None = None
    topic: str | None = None
    tone: str | None = None
    hosts: tuple[str, ...] = ()
    segments: tuple[PodcastSegment, ...] = ()
    events: tuple[PodcastEvent, ...] = ()
    voice_casting: dict[str, str] = field(default_factory=dict)
    voice_hints: dict[str, str] = field(default_factory=dict)
    tts_styles: dict[str, str] = field(default_factory=dict)
    pronunciation_overrides: dict[str, Any] = field(default_factory=dict)
    language: str = "en"
    series_id: str | None = None
    music_style: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "podcast_id": self.podcast_id,
            "title": self.title,
            "show_name": self.show_name,
            "topic": self.topic,
            "tone": self.tone,
            "hosts": list(self.hosts),
            "segments": [s.to_dict() for s in self.segments],
            "events": [e.to_dict() for e in self.events],
            "voice_casting": dict(self.voice_casting),
            "voice_hints": dict(self.voice_hints),
            "tts_styles": dict(self.tts_styles),
            "pronunciation_overrides": dict(self.pronunciation_overrides),
            "language": self.language,
            "music_style": self.music_style,
            "series_id": self.series_id,
        }
